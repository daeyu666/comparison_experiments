"""Train/evaluate paper-topology UAFL on the strict Augsburg-2 Wald x3 protocol.

Only *observed* 30m HSI supplies supervision. Input HSI90 was generated by
S2Diff-MH prepare_augsburg2_wald.py; reference MSI30 is real Sentinel-2 10m
aggregated to 30m. Never touch EnMAP10, synthetic x4, or full-inference labels.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import math
import random
import sys
from pathlib import Path

import numpy as np
import torch

THIS = Path(__file__).resolve().parent
sys.path.insert(0, str(THIS))
from augsburg2_wald_common import (
    WaldDataset, PROVENANCE, correct_msi, load_state, make_loaders,
    masked_l1, metrics_from_sums, metrics_sums, read_json,
    read_radiometry, require_wald, predict_uafl,
)
from model import build_uafl, parameter_count


def parser():
    p = argparse.ArgumentParser(description="Strict Augsburg-2 Wald UAFL x3 training")
    p.add_argument("--stage", choices=["train","test"], default="train")
    p.add_argument("--wald_root", default="./data/augsburg2_wald")
    p.add_argument("--radiometry_json", default="./data/calibration/Augsburg2_Wald_radiometry.json")
    p.add_argument("--checkpoint_dir", default="./comparison/UAFL/checkpoints/augsburg2_wald")
    p.add_argument("--log_dir", default="./comparison/UAFL/logs/augsburg2_wald")
    p.add_argument("--checkpoint", default="", help="test checkpoint; defaults to checkpoint_dir/best.pth.tar")
    p.add_argument("--resume", default="", help="own Wald last.pth.tar only; never x4/EnMAP10")
    p.add_argument("--train_patch_size", type=int, default=72)
    p.add_argument("--train_stride", type=int, default=6)
    p.add_argument("--eval_patch_size", type=int, default=48)
    p.add_argument("--min_valid_fraction", type=float, default=0.80)
    p.add_argument("--batch_size", type=int, default=1)
    p.add_argument("--num_workers", type=int, default=0)
    p.add_argument("--epochs", type=int, default=100)
    p.add_argument("--lr", type=float, default=1e-5)
    p.add_argument("--weight_decay", type=float, default=5e-5)
    p.add_argument("--eval_interval", type=int, default=5)
    p.add_argument("--save_interval", type=int, default=5)
    p.add_argument("--monitor", choices=["ref_sam","ref_psnr"], default="ref_sam")
    p.add_argument("--seed", type=int, default=10)
    p.add_argument("--device", default="cuda")
    return p


def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def file_sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def get_device(name):
    if name.startswith("cuda") and not torch.cuda.is_available():
        raise RuntimeError("CUDA is required by --device but is unavailable")
    return torch.device(name)


def rng_snapshot():
    return {
        "torch":torch.get_rng_state(),
        "cuda":torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
        "numpy":np.random.get_state(),
        "python":random.getstate(),
    }


def restore_rng(state):
    if not state:
        return
    torch.set_rng_state(state["torch"].cpu())
    np.random.set_state(state["numpy"])
    random.setstate(state["python"])
    if state.get("cuda") is not None and torch.cuda.is_available():
        torch.cuda.set_rng_state_all([value.cpu() for value in state["cuda"]])


def checkpoint(model, optimizer, epoch, best, args, sha, sigma):
    return {
        "protocol":"Augsburg-2-Wald-UAFL",
        "msi_source":PROVENANCE,
        "target":"observed_30m_HSI_only",
        "scale_ratio":3,
        "train_area":read_json(Path(args.wald_root)/"train"/"meta.json")["training_area"],
        "split_protocol_id":getattr(args, "split_protocol_id", "legacy_full_region_wald"),
        "test_bbox_30m":getattr(args, "test_bbox_30m", None),
        "wald_sigma":float(sigma),
        "radiometry_sha256":sha,
        "model":model.state_dict(),
        "optimizer":optimizer.state_dict() if optimizer else None,
        "epoch":int(epoch),
        "best_metric":float(best),
        "monitor":args.monitor,
        "args":vars(args),
        "rng":rng_snapshot(),
    }


@torch.no_grad()
def evaluate(model, loader, device, calibration):
    model.eval()
    total = [0.0,0,0.0,0]
    for batch in loader:
        gt = batch["gt"].to(device)
        lr = batch["lr_hsi"].to(device)
        msi = correct_msi(batch["hr_msi"].to(device),calibration)
        mask = batch["valid_mask"].to(device)
        pred = predict_uafl(model, lr, msi)
        sums=metrics_sums(pred,gt,mask)
        total=[a+b for a,b in zip(total,sums)]
    return metrics_from_sums(total)


def main():
    args=parser().parse_args()
    if args.epochs<=0 or args.batch_size<1 or args.eval_interval<1 or args.save_interval<1:
        raise ValueError("Invalid training schedule")
    if not 0.0 <= args.min_valid_fraction <= 1.0:
        raise ValueError("min_valid_fraction must be in [0,1]")
    if args.train_patch_size%24 or args.eval_patch_size%24 or args.train_stride%3:
        raise ValueError("UAFL Wald train/eval sizes must be multiples of 24; stride multiple of 3")
    if args.resume and args.stage!="train":
        raise ValueError("Use --checkpoint for test, not --resume")
    if args.resume and args.checkpoint:
        raise ValueError("Do not combine resume and test checkpoint")

    sigma=require_wald(args.wald_root)
    split_meta=read_json(Path(args.wald_root)/"train"/"meta.json")
    args.split_protocol_id=split_meta.get("protocol_id", "legacy_full_region_wald")
    args.test_bbox_30m=split_meta.get("test_bbox_30m")
    if args.split_protocol_id == "Augsburg2-Wald-center-holdout-v1":
        if args.train_patch_size != 24 or args.train_stride != 6 or args.eval_patch_size != 48:
            raise ValueError("Center-holdout UAFL requires train_patch=24, stride=6, eval_patch=48")
        for split in ("validation","test"):
            entry=read_json(Path(args.wald_root)/split/"meta.json")
            if entry.get("protocol_id") != args.split_protocol_id:
                raise ValueError("Wald UAFL split protocol ID mismatch: "+split)
    sha=file_sha256(args.radiometry_json)
    calibration=read_radiometry(args.radiometry_json, args.wald_root)
    seed_everything(args.seed)
    device=get_device(args.device)
    model=build_uafl(4).to(device)
    out=Path(args.checkpoint_dir)
    logs=Path(args.log_dir)
    if args.stage=="test":
        ckpt_path=Path(args.checkpoint or out/"best.pth.tar")
        state=load_state(ckpt_path,model,device=device)
        if (state["radiometry_sha256"]!=sha or abs(state["wald_sigma"]-sigma)>1e-8
            or state.get("split_protocol_id", "legacy_full_region_wald") != args.split_protocol_id
            or state.get("test_bbox_30m") != args.test_bbox_30m):
            raise ValueError("Wald checkpoint/calibration/sigma/heldout split provenance mismatch")
        test_set=WaldDataset(args.wald_root,"test", args.train_patch_size,
                             args.train_stride,args.eval_patch_size,args.min_valid_fraction)
        test_loader=torch.utils.data.DataLoader(test_set,batch_size=1,shuffle=False)
        scores=evaluate(model,test_loader,device,calibration)
        print(f"UAFL_WALD_TEST samples={len(test_set)} REF_PSNR={scores['ref_psnr']:.6f} "
              f"REF_SAM={scores['ref_sam']:.6f} REF_RMSE={scores['ref_rmse']:.8f}")
        return

    train_loader,val_loader,_unused_test,count=make_loaders(
        args.wald_root,batch_size=args.batch_size,train_patch=args.train_patch_size,
        train_stride=args.train_stride,eval_patch=args.eval_patch_size,
        min_valid_fraction=args.min_valid_fraction,workers=args.num_workers,
        include_test=False)
    optimizer=torch.optim.AdamW(model.parameters(),lr=args.lr,weight_decay=args.weight_decay)
    best=float("inf") if args.monitor=="ref_sam" else -float("inf")
    start=0
    if args.resume:
        state=load_state(args.resume,model,optimizer,device=device)
        if (state["radiometry_sha256"]!=sha or abs(state["wald_sigma"]-sigma)>1e-8
            or state["monitor"]!=args.monitor
            or state.get("split_protocol_id", "legacy_full_region_wald") != args.split_protocol_id
            or state.get("test_bbox_30m") != args.test_bbox_30m):
            raise ValueError("Resume checkpoint belongs to a different Wald protocol/split")
        start=int(state["epoch"])+1
        best=float(state["best_metric"])
        restore_rng(state.get("rng"))
    out.mkdir(parents=True,exist_ok=True)
    logs.mkdir(parents=True,exist_ok=True)
    history=logs/"history.csv"
    print(f"UAFL_AUGSBURG2_WALD train={count[0]} validation={count[1]} "
          f"patch={args.train_patch_size} stride={args.train_stride} "
          f"eval_patch={args.eval_patch_size} scale=x3 sigma={sigma} "
          f"parameters={parameter_count(model)} source={PROVENANCE} "
          f"EnMAP10_used=False train_augmentation=False monitoring={args.monitor}")

    for epoch in range(start,args.epochs):
        model.train()
        loss_sum,n=0.,0
        for batch in train_loader:
            gt=batch["gt"].to(device)
            lr=batch["lr_hsi"].to(device)
            msi=correct_msi(batch["hr_msi"].to(device),calibration)
            mask=batch["valid_mask"].to(device)
            optimizer.zero_grad(set_to_none=True)
            pred=predict_uafl(model,lr,msi)
            loss=masked_l1(pred,gt,mask)
            if not bool(torch.isfinite(loss)):
                raise FloatingPointError(f"UAFL Wald non-finite L1 at epoch {epoch+1}")
            loss.backward()
            optimizer.step()
            loss_sum+=float(loss.item())*gt.shape[0]
            n+=gt.shape[0]

        current=epoch+1
        row={"epoch":current,"train_l1":loss_sum/max(n,1),"val_ref_psnr":"",
             "val_ref_sam":"","val_ref_rmse":"","best":best}
        is_eval=current%args.eval_interval==0 or current==args.epochs
        if is_eval:
            metrics=evaluate(model,val_loader,device,calibration)
            score=metrics[args.monitor]
            improved=score<best if args.monitor=="ref_sam" else score>best
            if improved:
                best=float(score)
                torch.save(checkpoint(model,optimizer,epoch,best,args,sha,sigma),out/"best.pth.tar")
            row.update({"val_ref_psnr":metrics["ref_psnr"],"val_ref_sam":metrics["ref_sam"],
                        "val_ref_rmse":metrics["ref_rmse"],"best":best})
            print(f"EPOCH {current}/{args.epochs} L1={row['train_l1']:.7f} "
                  f"VAL_PSNR={metrics['ref_psnr']:.5f} VAL_SAM={metrics['ref_sam']:.5f} "
                  f"best_{args.monitor}={best:.6f} saved_best={improved}")
            with history.open("a",newline="",encoding="utf-8") as handle:
                writer=csv.DictWriter(handle,fieldnames=list(row))
                if handle.tell()==0:
                    writer.writeheader()
                writer.writerow(row)
        else:
            print(f"EPOCH {current}/{args.epochs} L1={row['train_l1']:.7f}")

        if is_eval or current%args.save_interval==0:
            torch.save(checkpoint(model,optimizer,epoch,best,args,sha,sigma),out/"last.pth.tar")

    print(f"TRAIN_COMPLETE best_{args.monitor}={best:.6f} best={out/'best.pth.tar'}")


if __name__=="__main__":
    main()
